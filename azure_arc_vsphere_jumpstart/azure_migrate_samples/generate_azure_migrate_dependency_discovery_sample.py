def build_summary_rows(process_rows, connection_rows):
    counts = defaultdict(
        lambda: {
            "processes": 0,
            "internal": 0,
            "external": 0,
            "patterns": set(),
            "signals": set(),
            "critical": 0,
        }
    )
    for row in process_rows:
        key = (row[0], row[1])
        counts[key]["processes"] += 1
    for row in connection_rows:
        key = (row[0], row[1])
        if row[6] == "external-service":
            counts[key]["external"] += 1
        else:
            counts[key]["internal"] += 1
        counts[key]["patterns"].add(row[12])
        counts[key]["signals"].add(row[20])
        if row[18] == "critical":
            counts[key]["critical"] += 1

    rows = []
    for (scenario, app_name), data in sorted(counts.items()):
        rows.append(
            [
                scenario,
                app_name,
                data["processes"],
                data["internal"],
                data["external"],
                data["critical"],
                "; ".join(sorted(data["patterns"])),
                "; ".join(sorted(data["signals"])),
            ]
        )
    return rows


